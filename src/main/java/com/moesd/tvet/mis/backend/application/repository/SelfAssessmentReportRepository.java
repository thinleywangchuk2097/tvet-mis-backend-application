package com.moesd.tvet.mis.backend.application.repository;

import java.util.List;
import java.util.Optional;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.NativeQuery;
import com.moesd.tvet.mis.backend.application.model.SelfAssessmentReport;
import jakarta.persistence.Tuple;

public interface SelfAssessmentReportRepository extends JpaRepository<SelfAssessmentReport, Long> {

	Optional<SelfAssessmentReport> findByApplicationNo(String applicationNo);

	// ------------------------------------------------------------------
	// Self Assessment Report details (verification page)
	// ------------------------------------------------------------------
	@NativeQuery("SELECT "
			+ "  sar.id, "
			+ "  sar.application_no, "
			+ "  sar.institute_id, "
			+ "  sar.service_id, "
			+ "  sar.status_id, "
			+ "  sar.total_score, "
			+ "  sar.grade, "
			+ "  sar.submitted_date, "
			+ "  sar.created_at, "
			+ "  sar.updated_at, "
			+ "  ir.registration_no, "
			+ "  ir.proposed_institute_name, "
			+ "  dcm.name AS status_name, "
			+ "  (SELECT "
			+ "    IFNULL( "
			+ "      JSON_ARRAYAGG( "
			+ "        JSON_OBJECT( "
			+ "          'id', qs.id, "
			+ "          'standardId', qs.standard_id, "
			+ "          'selfPoint', qs.self_point, "
			+ "          'earnedPoint', qs.earned_point, "
			+ "          'justification', qs.justification "
			+ "        ) "
			+ "      ), "
			+ "      JSON_ARRAY() "
			+ "    ) "
			+ "  FROM "
			+ "    tbl_self_assessment_report_quality_response qs "
			+ "  WHERE qs.application_no = sar.application_no) AS quality_standard_responses, "
			+ "  (SELECT "
			+ "    IFNULL( "
			+ "      JSON_ARRAYAGG( "
			+ "        JSON_OBJECT( "
			+ "          'id', m.id, "
			+ "          'userId', m.user_id, "
			+ "          'name', m.name, "
			+ "          'designation', m.designation "
			+ "        ) "
			+ "      ), "
			+ "      JSON_ARRAY() "
			+ "    ) "
			+ "  FROM "
			+ "    tbl_self_assessment_report_member m "
			+ "  WHERE m.application_no = sar.application_no "
			+ "    AND m.member_type = 'ACCREDITOR') AS accreditors, "
			+ "  (SELECT "
			+ "    IFNULL( "
			+ "      JSON_ARRAYAGG( "
			+ "        JSON_OBJECT( "
			+ "          'id', m.id, "
			+ "          'name', m.name, "
			+ "          'designation', m.designation "
			+ "        ) "
			+ "      ), "
			+ "      JSON_ARRAY() "
			+ "    ) "
			+ "  FROM "
			+ "    tbl_self_assessment_report_member m "
			+ "  WHERE m.application_no = sar.application_no "
			+ "    AND m.member_type = 'COORDINATOR') AS coordinators, "
			+ "  (SELECT "
			+ "    IFNULL( "
			+ "      JSON_ARRAYAGG( "
			+ "        JSON_OBJECT( "
			+ "          'id', d.id, "
			+ "          'documentName', d.document_name, "
			+ "          'attachmentType', d.attachment_type, "
			+ "          'url', d.upload_url "
			+ "        ) "
			+ "      ), "
			+ "      JSON_ARRAY() "
			+ "    ) "
			+ "  FROM "
			+ "    tbl_document_master d "
			+ "  WHERE d.application_no = sar.application_no COLLATE utf8mb4_general_ci) AS documents "
			+ "FROM "
			+ "  tbl_self_assessment_report_dtls sar "
			+ "  LEFT JOIN tbl_institute_registration_dtls ir "
			+ "    ON ir.institute_id = sar.institute_id "
			+ "  LEFT JOIN tbl_dropdown_child_master dcm "
			+ "    ON dcm.id = sar.status_id "
			+ "WHERE sar.application_no = ?")
	List<Tuple> getSelfAssessmentReportByApplicationNo(String applicationNo);

	// ------------------------------------------------------------------
	// List of Self Assessment Reports of the logged in institute
	// ------------------------------------------------------------------
	@NativeQuery("SELECT "
			+ "  sar.id, "
			+ "  sar.application_no, "
			+ "  sar.institute_id, "
			+ "  sar.status_id, "
			+ "  sar.total_score, "
			+ "  sar.grade, "
			+ "  sar.submitted_date, "
			+ "  ir.registration_no, "
			+ "  ir.proposed_institute_name, "
			+ "  dcm.name AS status_name, "
			+ "  (SELECT "
			+ "    IFNULL( "
			+ "      JSON_ARRAYAGG( "
			+ "        JSON_OBJECT( "
			+ "          'id', qs.id, "
			+ "          'standardId', qs.standard_id, "
			+ "          'selfPoint', qs.self_point, "
			+ "          'earnedPoint', qs.earned_point "
			+ "        ) "
			+ "      ), "
			+ "      JSON_ARRAY() "
			+ "    ) "
			+ "  FROM "
			+ "    tbl_self_assessment_report_quality_response qs "
			+ "  WHERE qs.application_no = sar.application_no) AS quality_standard_responses, "
			+ "  (SELECT "
			+ "    IFNULL( "
			+ "      JSON_ARRAYAGG( "
			+ "        JSON_OBJECT( "
			+ "          'id', d.id, "
			+ "          'documentName', d.document_name, "
			+ "          'attachmentType', d.attachment_type, "
			+ "          'url', d.upload_url "
			+ "        ) "
			+ "      ), "
			+ "      JSON_ARRAY() "
			+ "    ) "
			+ "  FROM "
			+ "    tbl_document_master d "
			+ "  WHERE d.application_no = sar.application_no COLLATE utf8mb4_general_ci) AS documents "
			+ "FROM "
			+ "  tbl_self_assessment_report_dtls sar "
			+ "  LEFT JOIN tbl_institute_registration_dtls ir "
			+ "    ON ir.institute_id = sar.institute_id "
			+ "  LEFT JOIN tbl_dropdown_child_master dcm "
			+ "    ON dcm.id = sar.status_id "
			+ "  INNER JOIN tbl_user u "
			+ "    ON u.user_id = ir.registration_no "
			+ "WHERE u.user_id = ? "
			+ "ORDER BY sar.id DESC")
	List<Tuple> getSelfAssessmentReportsByUserId(String userId);

	// ------------------------------------------------------------------
	// Basic Information : Institute details (tbl_institute_registration_dtls)
	// ------------------------------------------------------------------
	String INSTITUTE_SELECT = "SELECT "
			+ "  ir.institute_id, "
			+ "  ir.registration_no, "
			+ "  ir.application_no, "
			+ "  ir.proposed_institute_name, "
			+ "  ir.business_license_no, "
			+ "  ir.email_id, "
			+ "  ir.mobile_no, "
			+ "  ir.telephone_no, "
			+ "  ir.website, "
			+ "  ir.exact_location, "
			+ "  ir.dzongkhag_id, "
			+ "  dz.dzongkhag_name, "
			+ "  ir.key_contact_name, "
			+ "  ir.key_contact_designation, "
			+ "  ir.key_contact_mobile_no, "
			+ "  ir.bhutanese_employees, "
			+ "  ir.non_bhutanese_employees, "
			+ "  ir.ownership_type_id, "
			+ "  dcm1.name AS ownership_type, "
			+ "  ir.institute_type_id, "
			+ "  dcm2.name AS institute_type, "
			+ "  ir.status_id, "
			+ "  dcm3.name AS status_name, "
			+ "  ir.institute_renewal_date "
			+ "FROM "
			+ "  tbl_institute_registration_dtls ir "
			+ "  LEFT JOIN tbl_dzongkhag_master dz "
			+ "    ON dz.id = ir.dzongkhag_id "
			+ "  LEFT JOIN tbl_dropdown_child_master dcm1 "
			+ "    ON dcm1.id = ir.ownership_type_id "
			+ "  LEFT JOIN tbl_dropdown_child_master dcm2 "
			+ "    ON dcm2.id = ir.institute_type_id "
			+ "  LEFT JOIN tbl_dropdown_child_master dcm3 "
			+ "    ON dcm3.id = ir.status_id ";

	// tbl_user.user_id = tbl_institute_registration_dtls.registration_no
	@NativeQuery(INSTITUTE_SELECT
			+ "  INNER JOIN tbl_user u "
			+ "    ON u.user_id = ir.registration_no "
			+ "WHERE u.user_id = ?")
	List<Tuple> getInstituteDetailsByUserId(String userId);

	@NativeQuery(INSTITUTE_SELECT + "WHERE ir.institute_id = ?")
	List<Tuple> getInstituteDetailsByInstituteId(Integer instituteId);

	// ------------------------------------------------------------------
	// Basic Information : Trainer details (tbl_trainer_dtls)
	// ------------------------------------------------------------------
	@NativeQuery("SELECT "
			+ "  t.id, "
			+ "  t.citizen_id, "
			+ "  t.name, "
			+ "  t.email, "
			+ "  t.mobile_no, "
			+ "  t.joining_date, "
			+ "  t.work_experience, "
			+ "  t.work_permit_no, "
			+ "  t.specialization, "
			+ "  t.description, "
			+ "  dcm1.name AS gender, "
			+ "  dcm2.name AS qualification, "
			+ "  dcm3.name AS employment_type, "
			+ "  dcm4.name AS status_name "
			+ "FROM "
			+ "  tbl_institute_registration_dtls ir "
			+ "  INNER JOIN tbl_trainer_dtls t "
			+ "    ON t.institute_id = ir.institute_id "
			+ "  LEFT JOIN tbl_dropdown_child_master dcm1 "
			+ "    ON dcm1.id = t.gender_id "
			+ "  LEFT JOIN tbl_dropdown_child_master dcm2 "
			+ "    ON dcm2.id = t.qualification_id "
			+ "  LEFT JOIN tbl_dropdown_child_master dcm3 "
			+ "    ON dcm3.id = t.employment_type_id "
			+ "  LEFT JOIN tbl_dropdown_child_master dcm4 "
			+ "    ON dcm4.id = t.status_id "
			+ "WHERE ir.institute_id = ? "
			+ "ORDER BY t.name")
	List<Tuple> getTrainersByInstituteId(Integer instituteId);

	// ------------------------------------------------------------------
	// Basic Information : Course details
	// (tbl_accredited_course_dtls + tbl_non_accredited_course_dtls)
	// ------------------------------------------------------------------
	@NativeQuery("SELECT * FROM ( "
			+ "  SELECT "
			+ "    ac.application_no, "
			+ "    'Accredited (BQF)' AS course_type, "
			+ "    COALESCE(ncs.programme_title, cd.programme_title, cd.curriculum_title) AS programme_title, "
			+ "    dcm1.name AS certificate_level, "
			+ "    cd.total_program_duration, "
			+ "    ac.enrolment_capacity, "
			+ "    ac.fees_per_trainee, "
			+ "    ac.status_id, "
			+ "    dcm.name AS status_name, "
			+ "    ac.registration_date "
			+ "  FROM "
			+ "    tbl_institute_registration_dtls ir "
			+ "    INNER JOIN tbl_accredited_course_dtls ac "
			+ "      ON ac.institute_id = ir.institute_id "
			+ "    LEFT JOIN tbl_curriculum_development cd "
			+ "      ON cd.id = ac.curriculum_id "
			+ "    LEFT JOIN tbl_ncs_app_dtls ncs "
			+ "      ON ncs.id = cd.programme_id "
			+ "    LEFT JOIN tbl_dropdown_child_master dcm "
			+ "      ON dcm.id = ac.status_id "
			+ "    LEFT JOIN tbl_dropdown_child_master dcm1 "
			+ "      ON dcm1.id = cd.certificate_level_id "
			+ "  WHERE ir.institute_id = ?1 "
			+ "  UNION ALL "
			+ "  SELECT "
			+ "    na.application_no, "
			+ "    'Non-Accredited' AS course_type, "
			+ "    COALESCE(na.programme_title, na.course_title, cd.programme_title, cd.curriculum_title) AS programme_title, "
			+ "    dcm1.name AS certificate_level, "
			+ "    cd.total_program_duration, "
			+ "    na.enrolment_capacity, "
			+ "    na.fees_per_trainee, "
			+ "    na.status_id, "
			+ "    dcm.name AS status_name, "
			+ "    na.registration_date "
			+ "  FROM "
			+ "    tbl_institute_registration_dtls ir "
			+ "    INNER JOIN tbl_non_accredited_course_dtls na "
			+ "      ON na.institute_id = ir.institute_id "
			+ "    LEFT JOIN tbl_curriculum_development cd "
			+ "      ON cd.id = na.curriculum_id "
			+ "    LEFT JOIN tbl_dropdown_child_master dcm "
			+ "      ON dcm.id = na.status_id "
			+ "    LEFT JOIN tbl_dropdown_child_master dcm1 "
			+ "      ON dcm1.id = cd.certificate_level_id "
			+ "  WHERE ir.institute_id = ?1 "
			+ ") c "
			+ "ORDER BY c.course_type, c.programme_title")
	List<Tuple> getCoursesByInstituteId(Integer instituteId);

	// ------------------------------------------------------------------
	// Active (in process) report of the institute - prevents duplicates
	// ------------------------------------------------------------------
	@NativeQuery("SELECT "
			+ "  sar.application_no, "
			+ "  sar.status_id "
			+ "FROM "
			+ "  tbl_self_assessment_report_dtls sar "
			+ "WHERE sar.institute_id = ? "
			+ "  AND sar.status_id NOT IN (57, 58)")
	List<Tuple> getActiveSelfAssessmentReport(Integer instituteId);
}
