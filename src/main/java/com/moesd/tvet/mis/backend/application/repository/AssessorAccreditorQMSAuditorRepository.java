package com.moesd.tvet.mis.backend.application.repository;

import java.util.List;
import java.util.Optional;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.NativeQuery;
import com.moesd.tvet.mis.backend.application.model.AssessorAccreditorQMSAuditor;
import jakarta.persistence.Tuple;


public interface AssessorAccreditorQMSAuditorRepository extends JpaRepository<AssessorAccreditorQMSAuditor, Long>{
	@NativeQuery("SELECT "
					+ "  a.id, "
					+ "  a.application_no, "
					+ "  a.reference_no, "
					+ "  a.citizen_id, "
					+ "  a.full_name, "
					+ "  a.gender_id, "
					+ "  a.date_of_birth, "
					+ "  a.mobile_no, "
					+ "  a.email, "
					+ "  a.dzongkhag_id, "
					+ "  a.organization_name, "
					+ "  a.sector_id, "
					+ "  a.sector_name, "
					+ "  a.occupation_id, "
					+ "  a.occupation_name, "
					+ "  a.certification_level_id, "
					+ "  a.certification_level_name, "
					+ "  a.designation, "
					+ "  a.years_of_experience, "
					+ "  a.responsibility, "
					+ "  a.qms_training, "
					+ "  a.academic_background, "
					+ "  a.status_id, "
					+ "  a.created_at, "
					+ "  a.updated_at, "
					+ "  a.created_by, "
					+ "  a.updated_by, "
					+ "  a.remarks, "
					+ "  t.task_status_id, "
					+ "  (SELECT "
					+ "    JSON_ARRAYAGG( "
					+ "      JSON_OBJECT( "
					+ "        'id', w.id, "
					+ "        'organizationName', w.organization_name, "
					+ "        'designation', w.designation, "
					+ "        'year', w.year, "
					+ "        'responsibility', w.responsibility, "
					+ "        'createdAt', w.created_at, "
					+ "        'updatedAt', w.updated_at "
					+ "      ) "
					+ "    ) "
					+ "  FROM "
					+ "    tbl_auditor_work_experience w "
					+ "  WHERE w.application_no = a.application_no) AS work_experiences, "
					+ "  (SELECT "
					+ "    JSON_ARRAYAGG( "
					+ "      JSON_OBJECT( "
					+ "        'id', d.id, "
					+ "        'documentName', d.document_name, "
					+ "        'url', d.upload_url "
					+ "      ) "
					+ "    ) "
					+ "  FROM "
					+ "    tbl_document_master d "
					+ "  WHERE d.application_no = a.application_no) AS documents "
					+ "FROM "
					+ "  tbl_assessor_accreditor_auditor_registration a "
					+ "  LEFT JOIN tbl_task_dtls t "
					+ "    ON a.application_no = t.application_no "
					+ "WHERE a.application_no = ?")
		List<Tuple> getApplicationDetailByApplicationNo(String applicationNo);
	
		Optional<AssessorAccreditorQMSAuditor> findByApplicationNo(String applicationNo);
		
		
		@NativeQuery("SELECT "
						+ "  a.id, "
						+ "  a.application_no, "
						+ "  a.reference_no, "
						+ "  a.citizen_id, "
						+ "  a.full_name, "
						+ "  a.gender_id, "
						+ "  a.date_of_birth, "
						+ "  a.mobile_no, "
						+ "  a.email, "
						+ "  a.dzongkhag_id, "
						+ "  a.organization_name, "
						+ "  a.sector_id, "
						+ "  a.sector_name, "
						+ "  a.occupation_id, "
						+ "  a.occupation_name, "
						+ "  a.certification_level_id, "
						+ "  a.certification_level_name, "
						+ "  a.designation, "
						+ "  a.years_of_experience, "
						+ "  a.responsibility, "
						+ "  a.qms_training, "
						+ "  a.academic_background, "
						+ "  a.status_id, "
						+ "  a.created_at, "
						+ "  a.updated_at, "
						+ "  a.created_by, "
						+ "  a.updated_by, "
						+ "  a.remarks, "
						+ "  t.task_status_id, "
						+ "  (SELECT "
						+ "    JSON_ARRAYAGG( "
						+ "      JSON_OBJECT( "
						+ "        'id', "
						+ "        w.id, "
						+ "        'organizationName', "
						+ "        w.organization_name, "
						+ "        'designation', "
						+ "        w.designation, "
						+ "        'year', "
						+ "        w.year, "
						+ "        'responsibility', "
						+ "        w.responsibility, "
						+ "        'createdAt', "
						+ "        w.created_at, "
						+ "        'updatedAt', "
						+ "        w.updated_at "
						+ "      ) "
						+ "    ) "
						+ "  FROM "
						+ "    tbl_auditor_work_experience w "
						+ "  WHERE w.application_no = a.application_no) AS work_experiences "
						+ "   "
						+ "FROM "
						+ "  tbl_assessor_accreditor_auditor_registration a "
						+ "  LEFT JOIN tbl_task_dtls t "
						+ "    ON a.application_no = t.application_no "
						+ "WHERE ( "
						+ "    a.citizen_id = ? "
						+ "    OR a.reference_no = ? "
						+ "  ) "
						+ "  AND a.service_id = ?")
		
		List<Tuple> getApplicationByCitizenIdOrReferenceNo(String citizenId, String referenceNo, String serviceId);

		// Public list of approved (status 57) registrations for one service:
		// 32 = Assessor, 5 = Accreditor, 3 = QMS Auditor. No contact details are returned.
		@NativeQuery("SELECT "
						+ "  a.id, "
						+ "  a.registration_no, "
						+ "  a.full_name, "
						+ "  g.name AS gender, "
						+ "  a.organization_name, "
						+ "  a.designation, "
						+ "  dz.dzongkhag_name, "
						+ "  COALESCE(sec.sector_name, a.sector_name) AS sector_name, "
						+ "  COALESCE(occ.occupation_name, a.occupation_name) AS occupation_name, "
						+ "  COALESCE(lvl.name, a.certification_level_name) AS certification_level_name "
						+ "FROM "
						+ "  tbl_assessor_accreditor_auditor_registration a "
						+ "  LEFT JOIN tbl_dropdown_child_master g "
						+ "    ON g.id = a.gender_id "
						+ "  LEFT JOIN tbl_dzongkhag_master dz "
						+ "    ON dz.id = a.dzongkhag_id "
						+ "  LEFT JOIN tbl_sector_master sec ON sec.id = a.sector_id "
						+ "  LEFT JOIN tbl_occupation_master occ ON occ.id = a.occupation_id "
						+ "  LEFT JOIN tbl_dropdown_child_master lvl ON lvl.id = a.certification_level_id "
						+ "WHERE a.service_id = ? "
						+ "  AND a.status_id = 57 "
						+ "  AND a.registration_no IS NOT NULL "
						+ "ORDER BY a.full_name")
		List<Tuple> getRegisteredByServiceId(Integer serviceId);
		
		
		
}
